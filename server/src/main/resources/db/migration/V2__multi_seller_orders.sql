-- Migration V2: Multi-Seller Order Architecture & Security Enhancements

-- 1. Add public reference and tracking token to the parent order table
ALTER TABLE "order"
    ADD COLUMN IF NOT EXISTS "public_order_reference" VARCHAR(50),
    ADD COLUMN IF NOT EXISTS "tracking_token" VARCHAR(64);

-- Populate existing orders with reference and tracking token
UPDATE "order"
SET "public_order_reference" = 'AM-' || (1000 + id),
    "tracking_token" = md5(random()::text || clock_timestamp()::text || id::text)
WHERE "public_order_reference" IS NULL;

ALTER TABLE "order"
    ALTER COLUMN "public_order_reference" SET NOT NULL,
    ALTER COLUMN "tracking_token" SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS "idx_order_public_ref" ON "order"("public_order_reference");
CREATE UNIQUE INDEX IF NOT EXISTS "idx_order_tracking_token" ON "order"("tracking_token");

-- 2. Create the seller_orders table to represent each seller's fulfillment partition
CREATE TABLE IF NOT EXISTS "seller_orders" (
    "id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "order_id" BIGINT NOT NULL,
    "seller_id" BIGINT NOT NULL,
    "status" VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    "subtotal" DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY ("id"),
    CONSTRAINT "fk_seller_orders_order" FOREIGN KEY ("order_id") REFERENCES "order"("id") ON DELETE CASCADE,
    CONSTRAINT "fk_seller_orders_seller" FOREIGN KEY ("seller_id") REFERENCES "users"("id") ON DELETE CASCADE,
    CONSTRAINT "uk_seller_orders_order_seller" UNIQUE ("order_id", "seller_id")
);

-- 3. Add snapshot columns and seller_order_id to order_items
ALTER TABLE "order_items"
    ADD COLUMN IF NOT EXISTS "seller_order_id" BIGINT,
    ADD COLUMN IF NOT EXISTS "product_name_snapshot" VARCHAR(255),
    ADD COLUMN IF NOT EXISTS "thumbnail_snapshot" TEXT;

-- Populate seller_orders from existing order_items
INSERT INTO "seller_orders" ("order_id", "seller_id", "status", "subtotal", "created_at", "updated_at")
SELECT 
    oi."order_id",
    oi."seller_id",
    COALESCE(o."status", 'PENDING') AS "status",
    COALESCE(SUM(oi."price" * oi."quantity"), 0.00) AS "subtotal",
    COALESCE(o."created_at", CURRENT_TIMESTAMP) AS "created_at",
    CURRENT_TIMESTAMP AS "updated_at"
FROM "order_items" oi
JOIN "order" o ON o."id" = oi."order_id"
GROUP BY oi."order_id", oi."seller_id", o."status", o."created_at"
ON CONFLICT ("order_id", "seller_id") DO NOTHING;

-- Link order_items to seller_orders and populate snapshot data from product
UPDATE "order_items" oi
SET 
    "seller_order_id" = so."id",
    "product_name_snapshot" = COALESCE(
        (SELECT p."name" FROM "product" p WHERE p."id" = oi."product_id"),
        'Product #' || oi."product_id"
    ),
    "thumbnail_snapshot" = (SELECT p."thumbnail_url" FROM "product" p WHERE p."id" = oi."product_id")
FROM "seller_orders" so
WHERE oi."order_id" = so."order_id" AND oi."seller_id" = so."seller_id"
  AND oi."seller_order_id" IS NULL;

-- Add foreign key constraint to order_items for seller_order_id
ALTER TABLE "order_items"
    ADD CONSTRAINT "fk_order_items_seller_order" FOREIGN KEY ("seller_order_id") REFERENCES "seller_orders"("id") ON DELETE CASCADE;

-- 4. Useful performance indexes
CREATE INDEX IF NOT EXISTS "idx_seller_orders_seller_id" ON "seller_orders"("seller_id");
CREATE INDEX IF NOT EXISTS "idx_seller_orders_order_id" ON "seller_orders"("order_id");
CREATE INDEX IF NOT EXISTS "idx_order_items_seller_order_id" ON "order_items"("seller_order_id");
CREATE INDEX IF NOT EXISTS "idx_product_user_id" ON "product"("user_id");
CREATE INDEX IF NOT EXISTS "idx_product_category_id" ON "product"("category_id");
CREATE INDEX IF NOT EXISTS "idx_feedback_product_id" ON "feedback"("product_id");
CREATE INDEX IF NOT EXISTS "idx_feedback_seller_id" ON "feedback"("seller_id");
